package codegen

import (
	"fmt"
	"strings"

	"kitten/checker"
	"kitten/parser"
	"kitten/runtime"
)

// Error describes a code generation error and the position it relates to.
type Error struct {
	// File is the source file the error relates to. It is empty when the
	// program has no file identity.
	File string

	// Line is the one-based line of the offending syntax.
	Line int

	// Column is the one-based column of the offending syntax.
	Column int

	// Message explains the problem.
	Message string
}

// Error implements the error interface, formatting the position as [file:]line:column.
func (e *Error) Error() string {
	if e.File != "" {
		return fmt.Sprintf("%s:%d:%d: %s", e.File, e.Line, e.Column, e.Message)
	}
	return fmt.Sprintf("%d:%d: %s", e.Line, e.Column, e.Message)
}

// Generate translates a checked program into C source. The first module is the
// root module and the others are its imports; declarations from every module are
// emitted into one translation unit. Names from imported modules are mangled so
// that private declarations with the same name in different modules cannot
// collide.
//
// It consumes the checked result for resolved types and symbols and never
// re-resolves names or re-checks types. The output is deterministic for a given
// program: modules and declarations are emitted in order and generated names
// follow a fixed scheme.
//
// Generate requires a valid entry point: a zero-parameter function named "main"
// that returns no value, declared in the root module. A missing or malformed
// entry point is reported as an error rather than silently replaced. Generate
// returns an error rather than panicking on an inconsistent syntax tree.
func Generate(modules []*parser.Module, checked *checker.Result) (string, error) {
	if checked == nil {
		return "", &Error{Line: 1, Column: 1, Message: "cannot generate C without modules and a checked result"}
	}
	// The checker may append the implicit ReadFileResult prelude after the
	// loaded modules. Its result is authoritative; the caller's slice may be the
	// pre-prelude set.
	modules = checked.Modules
	if len(modules) == 0 {
		return "", &Error{Line: 1, Column: 1, Message: "cannot generate C without modules and a checked result"}
	}
	for _, module := range modules {
		if module == nil || module.Program == nil {
			return "", &Error{Line: 1, Column: 1, Message: "module has no parsed program"}
		}
	}

	g := &generator{
		modules:      modules,
		checked:      checked,
		buffer:       &strings.Builder{},
		literalNames: map[string]string{},
	}
	return g.generate()
}

// stringLiteral is one pooled static string literal. Its bytes are a static C
// string, so a literal needs no allocation and lives for the whole program.
type stringLiteral struct {
	// name is the C identifier of the pooled object.
	name string

	// escaped is the literal's bytes as a C string literal, including quotes.
	escaped string

	// length is the number of bytes in the literal, excluding the terminator.
	length int
}

// generator accumulates C source for one translation unit.
type generator struct {
	modules []*parser.Module
	checked *checker.Result
	buffer  *strings.Builder
	indent  int

	// temps numbers the temporaries generated for match statements, so that
	// generated names are unique and deterministic.
	temps int

	// literals holds the pooled string literals in the order they were first
	// needed, and literalNames maps a literal's C spelling to its pooled name so
	// that equal literals share one object.
	literals     []stringLiteral
	literalNames map[string]string
}

// newTemp returns the next deterministic temporary variable name.
func (g *generator) newTemp() string {
	name := fmt.Sprintf("%s%d", matchPrefix, g.temps)
	g.temps++
	return name
}

// write appends text without indentation or a newline.
func (g *generator) write(text string) {
	g.buffer.WriteString(text)
}

// writeIndent appends the current indentation.
func (g *generator) writeIndent() {
	for level := 0; level < g.indent; level++ {
		g.buffer.WriteString("    ")
	}
}

// line appends an indented, newline-terminated line.
func (g *generator) line(format string, args ...any) {
	g.writeIndent()
	if len(args) == 0 {
		g.buffer.WriteString(format)
	} else {
		fmt.Fprintf(g.buffer, format, args...)
	}
	g.buffer.WriteByte('\n')
}

// moduleStruct pairs a struct declaration with the ID of its module.
type moduleStruct struct {
	module      int
	declaration *parser.StructDecl
}

// moduleFunction pairs a function declaration with the ID of its module.
type moduleFunction struct {
	module      int
	declaration *parser.FunctionDecl
}

// generate emits the whole translation unit.
func (g *generator) generate() (string, error) {
	if err := g.validateEntryPoint(); err != nil {
		return "", err
	}

	prologue := g.buffer

	g.line("/* Generated by the Kitten compiler. Do not edit. */")
	g.line("#include %q", runtime.HeaderFileName)
	g.line("")

	if err := g.emitTypeForwardDeclarations(); err != nil {
		return "", err
	}
	if err := g.emitEnumDeclarations(); err != nil {
		return "", err
	}
	if err := g.emitUnionTagDeclarations(); err != nil {
		return "", err
	}
	if err := g.emitFunctionPrototypes(); err != nil {
		return "", err
	}
	if err := g.emitStructDefinitions(); err != nil {
		return "", err
	}
	if err := g.emitUnionDefinitions(); err != nil {
		return "", err
	}
	if err := g.emitStructConstructors(); err != nil {
		return "", err
	}
	if err := g.emitUnionConstructors(); err != nil {
		return "", err
	}
	if err := g.emitPreludeHelper(); err != nil {
		return "", err
	}

	// Function bodies are generated into a separate buffer, because a string
	// literal inside a body becomes a reference to a pooled static object and C
	// requires that object's declaration to appear before the use. Literals
	// appear only in function bodies: generated constructors take their values
	// as parameters.
	bodies := &strings.Builder{}
	g.buffer = bodies
	if err := g.emitFunctionDefinitions(); err != nil {
		return "", err
	}
	g.buffer = prologue
	g.emitStringLiterals()
	g.write(bodies.String())
	g.emitEntryPoint()

	return g.buffer.String(), nil
}

// emitStringLiterals writes one static object per distinct string literal used
// in a function body.
//
// A literal is a `static const ktn_string` whose data is a static C string, so
// evaluating it allocates nothing and its bytes are never collected; the length
// is the number of decoded bytes, which the compiler knows at generation time.
func (g *generator) emitStringLiterals() {
	if len(g.literals) == 0 {
		return
	}
	for _, literal := range g.literals {
		g.line("static const ktn_string %s = { %d, %s };", literal.name, literal.length, literal.escaped)
	}
	g.line("")
}

// rootModule returns the module being compiled, which holds the entry point.
func (g *generator) rootModule() *parser.Module {
	return g.modules[0]
}

// validateEntryPoint requires a zero-parameter, void-returning "main" in the
// root module. Imported modules are never entry points.
func (g *generator) validateEntryPoint() error {
	root := g.rootModule()
	for _, declaration := range root.Program.Declarations {
		function, ok := declaration.(*parser.FunctionDecl)
		if !ok || function == nil || function.Name != "main" {
			continue
		}

		info := g.checked.FunctionDecls[function]
		if info == nil {
			return g.errorAt(root.Path, function.At, "entry point main was not checked")
		}
		if len(info.ParameterTypes) != 0 {
			return g.errorAt(root.Path, function.At, "entry point main must take no parameters")
		}
		if !info.ReturnType.IsVoid() {
			return g.errorAt(root.Path, function.At, "entry point main must not return a value, but returns %s", info.ReturnType)
		}
		return nil
	}
	return g.errorAt(root.Path, parser.Position{Line: 1, Column: 1}, "program has no entry point: define fn main() in the root module")
}

// errorAt builds a code generation error attached to a file.
func (g *generator) errorAt(file string, position parser.Position, format string, args ...any) error {
	return &Error{
		File:    file,
		Line:    position.Line,
		Column:  position.Column,
		Message: fmt.Sprintf(format, args...),
	}
}

// structDeclarations returns every struct declaration, in module and source
// order.
func (g *generator) structDeclarations() []moduleStruct {
	var declarations []moduleStruct
	for _, module := range g.modules {
		for _, declaration := range module.Program.Declarations {
			if structDeclaration, ok := declaration.(*parser.StructDecl); ok && structDeclaration != nil {
				declarations = append(declarations, moduleStruct{module: module.ID, declaration: structDeclaration})
			}
		}
	}
	return declarations
}

